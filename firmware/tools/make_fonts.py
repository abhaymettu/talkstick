"""Render the stick's typefaces into anti-aliased VLW fonts and write them as a C header.

    uv run --with pillow python3 firmware/tools/make_fonts.py <inter-ttf-dir> [--preview out.png]

<inter-ttf-dir> is the extras/ttf folder of the Inter release (github.com/rsms/inter, SIL Open Font License 1.1).
Writes firmware/talkstick/fonts.h. Digits get one shared advance, so the clock and the timers do not jiggle.
VLW layout (what M5GFX's VLWfont::loadFont reads): six big-endian int32 (glyph count, version, size, 0, ascent,
descent), then seven int32 per glyph (code point, height, width, x advance, top above baseline, left offset, 0),
then each glyph's 8-bit alpha bitmap, row by row.
"""
import argparse
import struct
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ASCII = "".join(chr(c) for c in range(0x20, 0x7F)) + "\u00b7\u201c\u201d\u2026"

# name, file, pixel size, characters, tracking in 1/1000 em (negative tightens large type)
FONTS = [
    ("FONT_CLOCK", "InterDisplay-SemiBold.ttf", 58, "0123456789:-", -20),
    ("FONT_TITLE", "InterDisplay-SemiBold.ttf", 25, ASCII, -10),
    ("FONT_BODY", "Inter-Regular.ttf", 16, ASCII, 0),
    ("FONT_META", "Inter-Medium.ttf", 13, ASCII, 10),
]


def build(ttf: Path, size: int, chars: str, tracking: int):
    font = ImageFont.truetype(str(ttf), size)
    ascent, descent = font.getmetrics()
    track = round(size * tracking / 1000)
    digit_adv = max(round(font.getlength(d)) for d in "0123456789")
    glyphs = []
    for ch in sorted(set(chars)):
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        dx = x0
        if ch.isdigit():
            dx += (digit_adv - adv) // 2
            adv = digit_adv
        bitmap = b""
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            bitmap = img.tobytes()
        glyphs.append((ord(ch), h, w, max(1, adv + track), -y0, dx, bitmap))
    out = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for code, h, w, adv, top, dx, _ in glyphs:
        out += struct.pack(">7i", code, h, w, adv, top, dx, 0)
    for *_, bitmap in glyphs:
        out += bitmap
    return out, glyphs, ascent, descent


def draw_text(img: Image.Image, glyphs, x: int, baseline: int, text: str, rgb) -> None:
    """Preview: the same glyph placement the stick uses."""
    table = {g[0]: g for g in glyphs}
    for ch in text:
        g = table.get(ord(ch))
        if not g:
            continue
        _, h, w, adv, top, dx, bitmap = g
        if w and h:
            mask = Image.frombytes("L", (w, h), bitmap)
            img.paste(Image.new("RGB", (w, h), rgb), (x + dx, baseline - top), mask)
        x += adv


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("ttf_dir")
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "talkstick" / "fonts.h"))
    ap.add_argument("--preview")
    args = ap.parse_args()
    ttf_dir = Path(args.ttf_dir).expanduser()
    lines = ["// Generated by firmware/tools/make_fonts.py from Inter (SIL Open Font License 1.1, see OFL.txt).",
             "#pragma once", "#include <stdint.h>", ""]
    preview = Image.new("RGB", (480, 260), (14, 14, 16)) if args.preview else None
    y = 0
    for name, file, size, chars, tracking in FONTS:
        data, glyphs, ascent, descent = build(ttf_dir / file, size, chars, tracking)
        lines.append(f"// {file} {size}px, {len(glyphs)} glyphs, {len(data)} bytes")
        lines.append(f"static const uint8_t {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
        print(f"{name}: {file} {size}px, {len(glyphs)} glyphs, {len(data)} bytes, ascent {ascent} descent {descent}")
        if preview:
            y += ascent + 6
            draw_text(preview, glyphs, 8, y, "12:34" if chars.startswith("0") else "Thinking 0:42 Ready", (237, 237, 237))
            y += descent
    Path(args.out).write_text("\n".join(lines))
    print(f"wrote {args.out}")
    if preview:
        preview.save(args.preview)


if __name__ == "__main__":
    main()
